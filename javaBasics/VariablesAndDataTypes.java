class VariablesAndDataTypes{
    public static void main(String[] args) {
        // Primitive Data Types
        byte byteVar = 100;
        short shortVar = 5000;
        int intVar = 100000;
        long longVar = 15000000000L; // 'L' suffix is required
        
        float floatVar = 5.75f;       // 'f' suffix is required
        double doubleVar = 19.99d;
        
        char charVar = 'A';
        boolean booleanVar = true;

        System.out.println("Integer Value: " + intVar);
        System.out.println("Float Value: " + floatVar);
        System.out.println("Character Value: " + charVar);
        System.out.println("Boolean Value: " + booleanVar);
    }
}